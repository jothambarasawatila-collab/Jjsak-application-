export function generateNextAdmissionNumber(config: AdmissionNumberGenerationConfig, seq?: number): string {
  const currentSeq = seq !== undefined ? seq : config.currentSequence + 1;
  const formattedSeq = String(currentSeq).padStart(config.digitLength, '0');
  const yearStr = config.includeYear
    ? config.yearFormat === 'YYYY'
      ? '2026'
      : '26'
    : '';

  if (config.includeYear) {
    return `${config.prefix}${config.separator}${yearStr}${config.separator}${formattedSeq}`;
  }
  return `${config.prefix}${config.separator}${formattedSeq}`;
}

export function generateNemisUpi(): string {
  const letters = 'ABCDEFGHJKLMNPQRSTUVWXYZ';
  const randomLetters = Array.from({ length: 4 }, () => letters[Math.floor(Math.random() * letters.length)]).join('');
  const randomNumbers = Math.floor(1000 + Math.random() * 9000);
  return `${randomLetters}${randomNumbers}`;
}

