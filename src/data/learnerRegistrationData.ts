export function computeRegistrationStats(dossiers: LearnerMasterDossier[]): RegistrationWorkflowStats {
  const total = dossiers.length;
  let drafts = 0;
  let pendingBio = 0;
  let pendingApp = 0;
  let enrolled = 0;
  let rejected = 0;
  let male = 0;
  let female = 0;
  let g7 = 0;
  let g8 = 0;
  let g9 = 0;
  let sen = 0;

  for (const d of dossiers) {
    if (d.registrationStatus === 'DRAFT') drafts++;
    else if (d.registrationStatus === 'SUBMITTED') pendingBio++;
    else if (d.registrationStatus === 'BIOMETRICS_VERIFIED') pendingApp++;
    else if (d.registrationStatus === 'ENROLLED' || d.registrationStatus === 'REGISTRAR_APPROVED') enrolled++;
    else if (d.registrationStatus === 'REJECTED') rejected++;

    if (d.gender === 'Male') male++;
    else female++;

    if (d.academicPlacement?.enrolledGrade === 'Grade 7' || d.academicPlacement?.classCode?.includes('G7')) g7++;
    else if (d.academicPlacement?.enrolledGrade === 'Grade 8' || d.academicPlacement?.classCode?.includes('G8')) g8++;
    else if (d.academicPlacement?.enrolledGrade === 'Grade 9' || d.academicPlacement?.classCode?.includes('G9')) g9++;

    if (d.medicalDossier?.disabilityAndAccommodations?.hasDisability || d.medicalDossier?.disabilityAndAccommodations?.iepRequired) {
      sen++;
    }
  }

  return {
    totalRegistered: total,
    draftsCount: drafts,
    pendingBiometricsCount: pendingBio,
    pendingApprovalCount: pendingApp,
    enrolledCount: enrolled,
    rejectedCount: rejected,
    maleLearnersCount: male,
    femaleLearnersCount: female,
    grade7Count: g7,
    grade8Count: g8,
    grade9Count: g9,
    specialNeedsCount: sen,
  };
}

